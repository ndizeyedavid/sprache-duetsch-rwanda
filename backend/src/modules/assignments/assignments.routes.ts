import { Router } from "express";
import { z } from "zod";
import { asyncHandler } from "../../lib/async-handler.js";
import { ACADEMIC_ROLES } from "../../lib/roles.js";
import { requireAuth } from "../../middleware/auth.js";
import { requireRole } from "../../middleware/rbac.js";
import { validate } from "../../middleware/validate.js";
import { downloadAttachment,receiveFeedbackAudio,receiveFile } from "./assignment-files.js";
import * as c from "./assignments.controller.js";
import { assignmentBody,assignmentParams,assignmentStatusBody,draftBody,extensionBody,extensionParams,myListQuery,penaltyOverrideBody,reviewBody,staffListQuery,submissionParams } from "./assignments.schema.js";
import { feedbackBankRouter } from "./feedback-bank.routes.js";
export const assignmentsRouter = Router();
assignmentsRouter.use(requireAuth);
const student = requireRole("STUDENT"), staff = requireRole(...ACADEMIC_ROLES);
assignmentsRouter.use("/bank", feedbackBankRouter);
assignmentsRouter.get("/my", student, validate({ query: myListQuery }), asyncHandler(c.listMine));
assignmentsRouter.get("/my/:id", student, validate({ params: assignmentParams }), asyncHandler(c.getMine));
assignmentsRouter.put("/my/:id/draft", student, validate({ params: assignmentParams, body: draftBody }), asyncHandler(c.draft));
assignmentsRouter.post("/my/:id/submit", student, validate({ params: assignmentParams, body: draftBody }), asyncHandler(c.submit));
assignmentsRouter.post("/my/:id/files", student, validate({ params: assignmentParams }), receiveFile);
assignmentsRouter.get("/:id/files/:fileId", requireRole("STUDENT", ...ACADEMIC_ROLES), validate({ params: z.object({ id: z.uuid(), fileId: z.uuid() }) }), asyncHandler(downloadAttachment));
assignmentsRouter.get("/classes/:id/students", staff, validate({ params: assignmentParams }), asyncHandler(c.roster));
assignmentsRouter.get("/classes/:id/lessons", staff, validate({ params: assignmentParams }), asyncHandler(c.lessons));
assignmentsRouter.get("/", staff, validate({ query: staffListQuery }), asyncHandler(c.list));
assignmentsRouter.post("/", staff, validate({ body: assignmentBody }), asyncHandler(c.create));
assignmentsRouter.get("/:id", staff, validate({ params: assignmentParams }), asyncHandler(c.get));
assignmentsRouter.put("/:id", staff, validate({ params: assignmentParams, body: assignmentBody }), asyncHandler(c.update));
assignmentsRouter.post("/:id/submissions/:submissionId/review", staff, validate({ params: submissionParams, body: reviewBody }), asyncHandler(c.review));

assignmentsRouter.patch('/:id/status', staff, validate({ params: assignmentParams, body: assignmentStatusBody }), asyncHandler(c.status));
assignmentsRouter.post('/:id/duplicate', staff, validate({ params: assignmentParams }), asyncHandler(c.duplicate));
assignmentsRouter.delete('/:id', staff, validate({ params: assignmentParams }), asyncHandler(c.remove));
assignmentsRouter.get('/:id/export', staff, validate({ params: assignmentParams }), asyncHandler(c.exportResults));

assignmentsRouter.post('/:id/feedback-audio', staff, validate({ params: assignmentParams }), receiveFeedbackAudio);
assignmentsRouter.patch('/:id/submissions/:submissionId/penalty', staff, validate({ params: submissionParams, body: penaltyOverrideBody }), asyncHandler(c.penalty));
assignmentsRouter.put('/:id/extensions/:studentId', staff, validate({ params: extensionParams, body: extensionBody }), asyncHandler(c.extend));
assignmentsRouter.delete('/:id/extensions/:studentId', staff, validate({ params: extensionParams }), asyncHandler(c.unextend));
